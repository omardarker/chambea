function uniq<T>(arr: T[]): T[] {
  return Array.from(new Set(arr));
}

export const workers: Worker[] = seeds.map((s) => ({
  id: s.id,
  name: s.name,
  hue: s.hue,
  headline: s.headline,
  bio: s.bio,
  districts: uniq([...zones[s.zone], ...(s.extraDistricts ?? [])]),
  subcategoryIds: s.subs,
  identityVerified: s.identityVerified ?? false,
  backgroundChecked: s.backgroundChecked ?? false,
  certifications: s.certs ?? [],
  education: s.education ?? [],
  experience: s.experience,
  portfolio: s.portfolio.map(([title, subcategoryId, district], i): PortfolioItem => ({
    id: `${s.id}-p${i}`,
    title,
    subcategoryId,
    district,
    tone: (s.hue + i * 47) % 360,
  })),
  rating: s.rating,
  reviewCount: s.reviewCount,
  jobsDone: s.jobsDone,
  memberSince: s.memberSince,
  responseMinutes: s.responseMinutes,
  offersVisit: s.offersVisit ?? false,
  visitFee: s.visitFee ?? 0,
}));

export const services: Service[] = seeds.flatMap((s) =>
  s.services.map(([subcategoryId, title, price, unit, includesMaterials, durationLabel, description], i): Service => ({
    id: `${s.id}-s${i}`,
    workerId: s.id,
    subcategoryId,
    title,
    description,
    price,
    unit,
    includesMaterials,
    durationLabel,
  })),
);

const workerMap = new Map(workers.map((w) => [w.id, w]));
const serviceMap = new Map(services.map((s) => [s.id, s]));

export function getWorker(id: string): Worker | undefined {
  return workerMap.get(id);
}

export function getService(id: string): Service | undefined {
  return serviceMap.get(id);
}

export function servicesOf(workerId: string): Service[] {
  return services.filter((s) => s.workerId === workerId);
}

export function workersFor(subcategoryId: string): Worker[] {
  return workers.filter((w) => w.subcategoryIds.includes(subcategoryId));
}

